import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

// Resolve the Playwright CLI directly rather than shelling out to npx, which
// behaves differently across Windows shells.
const playwrightCli = createRequire(import.meta.url).resolve('@playwright/test/cli');

/**
 * Regenerates docs/TEST-CASES.md from the suites themselves, so the
 * traceability document can never drift from the tests it claims to describe.
 * Run with `npm run docs:cases`.
 */

const UI_GROUP_ORDER = [
  'Book CRUD',
  'Catalog browsing',
  'Book form validation',
  'Edge cases',
  'Dynamic UI states',
  'Cart',
  'Accessibility',
  'Regressions',
];

const API_GROUP_ORDER = [
  'GET /api/books',
  'GET /api/books/:id',
  'POST /api/books',
  'PUT /api/books/:id',
  'PATCH /api/books/:id',
  'DELETE /api/books/:id',
  'POST /api/books validation',
  'PUT and PATCH validation',
  'Query parameter validation',
  'Boundary values',
  'Empty and whitespace input',
  'Unusual content',
  'Payload and pagination limits',
  'Cart API',
  'Error contract',
  'Support endpoints',
  'Tenant isolation',
];

function listTests(args) {
  const raw = execFileSync(
    process.execPath,
    [playwrightCli, 'test', ...args, '--list', '--reporter=json'],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  );
  const json = JSON.parse(raw.slice(raw.indexOf('{')));

  const rows = [];
  const walk = (suites, file, group) => {
    for (const suite of suites ?? []) {
      const nextFile = suite.file ?? file;
      const nextGroup = suite.title && suite.title !== nextFile ? suite.title : group;
      for (const spec of suite.specs ?? []) {
        const match = /^([A-Z0-9]+-\d+)\s+(.*)$/.exec(spec.title);
        rows.push({
          file: nextFile,
          group: nextGroup ?? '',
          id: match ? match[1] : '',
          title: match ? match[2] : spec.title,
          core: (spec.tags ?? []).includes('core'),
        });
      }
      walk(suite.suites, nextFile, nextGroup);
    }
  };
  walk(json.suites);
  return rows;
}

function section(rows, dir, order, withBrowsers) {
  const groups = new Map();
  for (const row of rows) {
    const key = `${row.group}\u0000${row.file}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(row);
  }

  const sorted = [...groups.entries()].sort((a, b) => {
    const rank = (key) => {
      const index = order.indexOf(key.split('\u0000')[0]);
      return index < 0 ? order.length : index;
    };
    return rank(a[0]) - rank(b[0]);
  });

  const out = [];
  for (const [key, items] of sorted) {
    const [group, file] = key.split('\u0000');
    out.push(`\n### ${group}\n`);
    out.push(`\`${dir}${file}\`\n`);
    out.push(withBrowsers ? '| ID | Test | Browsers |' : '| ID | Test |');
    out.push(withBrowsers ? '| --- | --- | --- |' : '| --- | --- |');
    for (const item of items) {
      const browsers = item.core ? 'all three' : 'chromium';
      out.push(
        withBrowsers
          ? `| ${item.id || '—'} | ${item.title} | ${browsers} |`
          : `| ${item.id || '—'} | ${item.title} |`,
      );
    }
    out.push('');
  }
  return out.join('\n');
}

const ui = listTests(['--project=chromium']);
const api = listTests(['--config=playwright.api.config.ts']);
const coreCount = ui.filter((row) => row.core).length;
const executions = ui.length + coreCount * 2;

const header = `# Test case inventory

<!-- Generated by scripts/generate-test-cases.mjs. Run \`npm run docs:cases\` to refresh. -->

Every automated test carries an ID in its title, so a case in this document and
the code that proves it stay linked. Running \`npm run test:ui -- --grep BK-003\`
executes exactly the case listed here.

| Prefix | Area |
| --- | --- |
| \`BK-\` | Book CRUD through the UI |
| \`CAT-\` | Catalog browsing, search, filtering, sorting |
| \`VAL-\` | Form validation, negative cases |
| \`EDG-\` | Boundary values, unicode, empty states |
| \`DYN-\` | Loading states, debouncing, race conditions |
| \`CRT-\` | Cart behaviour |
| \`A11Y-\` | Accessibility, keyboard, axe-core |
| \`REG-\` | Regression cover for logged defects |
| \`API-\` | REST API and contract |

**Coverage:** ${ui.length} UI cases and ${api.length} API cases. The UI figure counts each case
once; ${coreCount} of them are tagged \`@core\` and additionally run on Firefox and WebKit,
giving ${executions} UI executions per full run.

---

## UI suite
`;

const body = `${header}${section(ui, 'tests/ui/specs/', UI_GROUP_ORDER, true)}
---

## API suite
${section(api, 'tests/api/specs/', API_GROUP_ORDER, false)}`;

writeFileSync('docs/TEST-CASES.md', body, 'utf8');
console.log(
  `docs/TEST-CASES.md: ${ui.length} UI cases (${coreCount} @core), ${api.length} API cases, ${executions} UI executions`,
);
